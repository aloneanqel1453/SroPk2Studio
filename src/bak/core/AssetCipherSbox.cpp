std::wstring LowerExt(const std::wstring& name) {
    const size_t dot = name.find_last_of(L'.');
    if (dot == std::wstring::npos) return std::wstring();
    std::wstring ext = name.substr(dot);
    for (wchar_t& c : ext) c = (wchar_t)towlower(c);
    return ext;
}

const unsigned char* MapForExt(const std::wstring& ext) {
    if (ext == L".bms") return kMapBms;
    if (ext == L".bsr") return kMapBsr;
    if (ext == L".ddj") return kMapDdj;
    if (ext == L".txt") return kMapTxt;
    return kMapDef;                       // .ban/.bmt/.bsk/.efp/.ifo/.mfo/... default
}

// A file that begins with one of these is a real, plaintext container (a JMXV
// asset or a media/image format) - it is NOT encrypted and must never be run
// through a substitution table. The same list, applied to a DECRYPTED buffer,
// is a decisive "this came out right" signal.
bool StartsWithKnownMagic(const u8* d, size_t n) {
    static const struct { const char* m; size_t len; } kMagics[] = {
        { "JMXV", 4 }, { "RIFF", 4 }, { "OggS", 4 }, { "ID3", 3 },
        { "DDS ", 4 }, { "\x89" "PNG", 4 }, { "\xFF\xD8\xFF", 3 }, { "GIF8", 4 },
    };
    for (const auto& s : kMagics)
        if (n >= s.len && std::memcmp(d, s.m, s.len) == 0) return true;
    return false;
}

void ByteStats(const u8* d, size_t n, int& zerosPc, int& printPc) {
    const size_t look = n < 4096 ? n : 4096;
    if (look == 0) { zerosPc = printPc = 0; return; }
    size_t z = 0, p = 0;
    for (size_t i = 0; i < look; ++i) {
        const u8 b = d[i];
        if (b == 0) ++z;
        else if ((b >= 0x20 && b <= 0x7E) || b == '\r' || b == '\n' || b == '\t') ++p;
    }
    zerosPc = (int)(z * 100 / look);
    printPc = (int)(p * 100 / look);
}

