// ============================================================================
//  SRO Asset Studio - core/I18n.h
//
//  Menu/UI language follows the PC's language automatically:
//    Turkish PC   -> Turkish menus
//    English PC   -> English menus
//    Arabic PC    -> Arabic menus (right-to-left aware)
//    anything else-> English (universal fallback)
//
//  Design: the Turkish source string IS the translation key. Wrap a UI literal
//  with T(L"..."). At Turkish the key returns itself (plus a tiny fix-table that
//  Turkifies the few English-authored labels); at English/Arabic it is looked up
//  in a table, and any missing entry falls back to the source so nothing ever
//  shows blank. Language is detected once at startup - the user just changes
//  their Windows language and restarts.
// ============================================================================
#pragma once

