// ============================================================================
//  SRO Asset Studio - core/AssetCipherProfiles.h
//
//  Known per-asset ciphers, so an archive opens WITHOUT the game running and
//  WITHOUT anything being remembered between sessions.
//
//  Where this came from: the shard's own crypto module (DevKit_DLL.dll) is
//  dropped, loaded and deleted by the client, so it exists only in memory. Its
//  CJArchiveFm::Decryption is a two-table stream cipher:
//
//      ks[pos] = (A[pos % 211] - B[pos % 493]) & 0xFF      // byte subtract
//      data[i] ^= ks[start + i]
//
//  Period is 211*493 = 104 023, which is why the stream looks unstructured.
//  Only the two tables are shard data; the construction is the same everywhere,
//  so a new shard needs a new profile here, not new code.
//
//  SAFETY - this is why a wrong profile can never corrupt anything: a profile is
//  never applied on the strength of a file name or a folder. It is tried against
//  a real encrypted asset from the archive and accepted ONLY if the result
//  carries the correct JMXV magic AND parses as a structurally sane header
//  (see PlausibleJmxvBody). Two shards with identical file names but different
//  keys therefore cannot be mixed up - the wrong one simply fails the test.
// ============================================================================
